"""Generate Metal compute kernels and a Swift pass table from the Anime4K
CNN shaders in assets/shaders (MIT, bloc97).

usage: python3 tvos/tools/anime4k_to_metal.py
writes tvos/KazumiTV/Sources/Anime4K/Anime4KKernels.metal
       tvos/KazumiTV/Sources/Anime4K/Anime4KPasses.swift
"""
import os

import anime4k_ir as ir

HERE = os.path.dirname(os.path.abspath(__file__))
SHADER_DIR = os.path.join(HERE, "../../assets/shaders")
OUT_DIR = os.path.join(HERE, "../KazumiTV/Sources/Anime4K")


def lit(x):
    v = float(x)
    s = format(v, ".9g")
    if "e" not in s and "." not in s:
        s += ".0"
    return s + "f"


def mat(m):
    cols = [", ".join(lit(v) for v in m[i * 4:(i + 1) * 4]) for i in range(4)]
    return "float4x4(" + ", ".join(f"float4({c})" for c in cols) + ")"


def var(tex, binds, dx, dy):
    i = binds.index(tex)
    n = lambda v: f"m{-v}" if v < 0 else str(v)
    return f"s{i}_{n(dx)}_{n(dy)}"


def gen_pass(sid, idx, p):
    name = f"{sid}_p{idx}"
    args = [f"texture2d<float, access::sample> t{i} [[texture({i})]]" for i in range(len(p.binds))]
    args.append(f"texture2d<float, access::write> outTex [[texture({len(p.binds)})]]")
    args.append("uint2 gid [[thread_position_in_grid]]")
    lines = [f"// {p.desc}", f"kernel void {name}(" + ",\n    ".join(args) + ") {",
             "    const uint w = outTex.get_width(), h = outTex.get_height();",
             "    if (gid.x >= w || gid.y >= h) return;"]
    if p.kind == "depth_to_space":
        lines.append("    const uint2 lo = gid / 2;")
        lines.append("    const uint ch = (gid.y & 1) * 2 + (gid.x & 1);")
        cs = []
        for c, tex in enumerate(p.d2s):
            i = p.binds.index(tex)
            if f"const float l{i} " not in "\n".join(lines):
                lines.append(f"    const float l{i} = t{i}.read(lo)[ch];")
            cs.append(f"l{i}")
        main = p.binds.index("MAIN")
        lines.append("    const float2 pos = (float2(gid) + 0.5f) / float2(w, h);")
        lines.append(f"    const float4 base = t{main}.sample(linearClamp, pos);")
        lines.append(f"    outTex.write(float4({', '.join(cs)}) + base, gid);")
        lines.append("}")
        return name, "\n".join(lines)

    lines.append("    const int2 p = int2(gid);")
    lines.append("    const int2 maxc = int2(int(w) - 1, int(h) - 1);")
    seen = set()
    for t in p.terms:
        v = var(t.tex, p.binds, t.dx, t.dy)
        if v in seen:
            continue
        seen.add(v)
        i = p.binds.index(t.tex)
        if t.dx == 0 and t.dy == 0:
            lines.append(f"    const float4 {v} = t{i}.read(gid);")
        else:
            lines.append(f"    const float4 {v} = t{i}.read(uint2(clamp(p + int2({t.dx}, {t.dy}), int2(0), maxc)));")
    lines.append(f"    float4 r = float4({', '.join(lit(b) for b in p.bias)});")
    for t in p.terms:
        v = var(t.tex, p.binds, t.dx, t.dy)
        x = {"id": v, "pos": f"max({v}, 0.0f)", "neg": f"max(-{v}, 0.0f)"}[t.sign]
        lines.append(f"    r += {mat(t.matrix)} * {x};")
    if p.kind == "conv_add_main":
        lines.append(f"    r += t{p.binds.index('MAIN')}.read(gid);")
    lines.append("    outTex.write(r, gid);")
    lines.append("}")
    return name, "\n".join(lines)


def main():
    metal = ["// Generated by tvos/tools/anime4k_to_metal.py from assets/shaders. Do not edit.",
             "// Anime4K v3.2 by bloc97, MIT License: https://github.com/bloc97/Anime4K",
             "#include <metal_stdlib>", "using namespace metal;", "",
             "constexpr sampler linearClamp(coord::normalized, address::clamp_to_edge, filter::linear);", ""]
    swift = ["// Generated by tvos/tools/anime4k_to_metal.py. Do not edit.", "",
             "/// One Anime4K pass: a compute kernel, the textures it reads (in binding",
             "/// order), the texture it writes, and the size of its output.",
             "struct Anime4KPass {", "    let kernel: String", "    let binds: [String]", "    let save: String",
             "    let sizeOf: String", "    let scale: Int", "}", "",
             "enum Anime4KPasses {", "    static let shaders: [String: [Anime4KPass]] = ["]
    for sid, fname in ir.SHADERS.items():
        passes = ir.parse(open(os.path.join(SHADER_DIR, fname)).read())
        swift.append(f'        "{sid}": [')
        for idx, p in enumerate(passes):
            name, code = gen_pass(sid, idx, p)
            metal.append(code)
            metal.append("")
            binds = ", ".join(f'"{b}"' for b in p.binds)
            swift.append(f'            Anime4KPass(kernel: "{name}", binds: [{binds}], save: "{p.save}", sizeOf: "{p.size_of}", scale: {p.scale}),')
        swift.append("        ],")
    swift += ["    ]", "}", ""]
    os.makedirs(OUT_DIR, exist_ok=True)
    open(os.path.join(OUT_DIR, "Anime4KKernels.metal"), "w").write("\n".join(metal))
    open(os.path.join(OUT_DIR, "Anime4KPasses.swift"), "w").write("\n".join(swift))
    print("ok")


if __name__ == "__main__":
    main()
